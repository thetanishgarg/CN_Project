#!/bin/bash
# nginx edge: TLS termination + load balancer
#   Phase 1: Task D + E    Phase 2: Ext D (HA failover) + Ext E (standby edge)
#
#   ./edge/nginx-script.sh start [primary|standby]   write config from config.env, test, start
#                                               (role auto-detected: Mac 2 = primary,
#                                                STANDBY_EDGE_IP = standby)
#   ./edge/nginx-script.sh stop     stop nginx
#   ./edge/nginx-script.sh reload   re-read config.env (new backend IPs) without downtime
#   ./edge/nginx-script.sh logs     live access log: client ip:port, TLS, which backend served it
#   ./edge/nginx-script.sh status   is it running / listening?
#
# Certificates: ./edge/mac2-certs.sh on Mac 2; on the standby Mac import them with
# ./edge/mac2-import-certs.sh (the private key is never stored in git).
set -e
cd "$(dirname "$0")/.."
source ./config.env

N="${NGINX_PREFIX:-$HOME/cn-phase1/edge/nginx}"
CERTS="$N/certs"
# Overrides only for testing on one laptop; leave unset in the demo
BACKEND_A="${BACKEND_A:-$MAC3_IP:$BACKEND_A_PORT}"
BACKEND_B="${BACKEND_B:-$MAC4_IP:$BACKEND_B_PORT}"
PORT="${PORT:-$HTTPS_PORT}"
SUDO="sudo"; [ "$PORT" -ge 1024 ] && SUDO=""
NGINX="$SUDO nginx -p $N -c conf/nginx.conf"

# ---- which edge am I? (shown in the X-Edge response header) ----
detect_role() {
  local ip; ip=$(ipconfig getifaddr "$(route -n get default 2>/dev/null | awk '/interface:/{print $2}')" 2>/dev/null || true)
  if [ -n "${1:-}" ]; then ROLE="$1"
  elif [ "$ip" = "$STANDBY_EDGE_IP" ] && [ "$ip" != "$MAC2_IP" ]; then ROLE="standby"
  else ROLE="primary"; fi
  case "$ROLE" in
    primary) EDGE_NAME="mac2-primary" ;;
    standby) EDGE_NAME="mac3-standby" ;;
    *) echo "role must be primary or standby"; exit 1 ;;
  esac
}

write_conf() {
mkdir -p "$N/conf" "$N/logs" "$N/run" "$N/temp"
[ -f "$CERTS/app.$PROJECT_DOMAIN.crt" ] || {
  echo "No certificate in $CERTS"
  echo "  Mac 2:   ./edge/mac2-certs.sh"
  echo "  standby: ./edge/mac2-import-certs.sh <bundle from Mac 2>"; exit 1; }
cat > "$N/conf/nginx.conf" <<EOF
# GENERATED by edge/nginx-script.sh from config.env - edit the script, not this file
# Edge role: $ROLE ($EDGE_NAME)
worker_processes 1;

error_log logs/error.log;
pid run/nginx.pid;

events {
    worker_connections 1024;
}

http {
    # client ip:ephemeral port, TLS version, HTTP version, request, status, which backend
    log_format edge '\$time_local \$remote_addr:\$remote_port \$ssl_protocol \$server_protocol '
                    '"\$request" \$status upstream=\$upstream_addr (\$upstream_status)';
    access_log logs/access.log edge;

    client_body_temp_path temp/body;
    proxy_temp_path       temp/proxy;
    fastcgi_temp_path     temp/fastcgi;
    uwsgi_temp_path       temp/uwsgi;
    scgi_temp_path        temp/scgi;

    # Round-robin load balancing.
    # Ext D - passive health check: a backend that fails once (refused / timeout)
    # is marked DOWN for 10 s and skipped; after 10 s nginx tries it again and,
    # if it answers, it is back in the rotation automatically.
    upstream backend_pool {
        server $BACKEND_A max_fails=1 fail_timeout=10s;   # Backend A (Mac 3)
        server $BACKEND_B max_fails=1 fail_timeout=10s;   # Backend B (Mac 4)
    }

    server {
        listen $PORT ssl;
        http2 on;
        server_name app.$PROJECT_DOMAIN api.$PROJECT_DOMAIN;

        ssl_certificate     $CERTS/app.$PROJECT_DOMAIN.crt;
        ssl_certificate_key $CERTS/app.$PROJECT_DOMAIN.key;
        ssl_protocols TLSv1.2 TLSv1.3;

        # Which edge + which backend answered (Ext D / Ext E evidence)
        add_header X-Edge     "$EDGE_NAME" always;
        add_header X-Upstream \$upstream_addr always;

        location / {
            # TLS ends here; nginx -> backend is plain HTTP on the LAN
            proxy_pass http://backend_pool;

            proxy_http_version 1.1;

            proxy_set_header Host \$host;
            proxy_set_header X-Real-IP \$remote_addr;
            proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
            proxy_set_header X-Forwarded-Proto https;

            # Ext D - failover. Process stopped -> connection refused -> instant retry.
            # Mac off / unplugged -> no reply -> give up after 2 s, retry on the other.
            proxy_connect_timeout 2s;
            proxy_read_timeout    5s;
            proxy_next_upstream   error timeout http_502 http_503;
            proxy_next_upstream_tries 2;
        }
    }
}
EOF
echo "Config written: $N/conf/nginx.conf   (role: $ROLE, X-Edge: $EDGE_NAME)"
echo "  https://app.$PROJECT_DOMAIN:$PORT  ->  A=$BACKEND_A  B=$BACKEND_B"
}

case "${1:-start}" in
start)
  detect_role "${2:-}"
  write_conf
  $NGINX -t
  if [ -f "$N/run/nginx.pid" ] && $SUDO kill -0 "$(cat "$N/run/nginx.pid")" 2>/dev/null; then
    $NGINX -s reload; echo "nginx was running - reloaded with new config."
  else
    $NGINX; echo "nginx started. Watch requests with: ./edge/nginx-script.sh logs"
  fi ;;
reload) detect_role "${2:-}"; write_conf; $NGINX -t && $NGINX -s reload && echo "reloaded." ;;
stop)   $NGINX -s stop && echo "nginx stopped." ;;
logs)   tail -f "$N/logs/access.log" ;;
status) lsof -nP -iTCP:"$PORT" -sTCP:LISTEN 2>/dev/null || $SUDO lsof -nP -iTCP:"$PORT" -sTCP:LISTEN || echo "nothing listening on $PORT" ;;
*)      sed -n '2,15p' "$0" ;;
esac
